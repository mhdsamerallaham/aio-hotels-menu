/**
 * Safe field resolver ensuring string primitive returns for React rendering
 */
const safeResolve = (val, lang = 'tr') => {
  if (!val) return '';
  if (typeof val === 'string') {
    const trimmed = val.trim();
    if (trimmed.startsWith('{')) {
      try {
        const parsed = JSON.parse(trimmed);
        return safeResolve(parsed, lang);
      } catch {
        return val;
      }
    }
    return val;
  }
  if (typeof val === 'object' && val !== null) {
    const picked = val[lang] || val.tr || val.en || val.TR || val.EN || Object.values(val)[0];
    if (typeof picked === 'object' && picked !== null) {
      return safeResolve(picked, lang);
    }
    return String(picked !== undefined && picked !== null ? picked : '');
  }
  return String(val || '');
};

/**
 * Localization helper for categories
 */
export const getLocalizedCategory = (category, lang = 'tr') => {
  if (!category) return null;

  return {
    ...category,
    name: safeResolve(category.name, lang),
    shortName: safeResolve(category.shortName || category.name, lang),
    subtitle: safeResolve(category.subtitle, lang),
    badge: safeResolve(category.badge, lang),
  };
};

/**
 * Localization helper for product option groups
 */
export const getLocalizedOptionGroups = (product, lang = 'tr') => {
  if (!product) return [];

  // 1. Explicit option_groups array on product
  if (Array.isArray(product.option_groups) && product.option_groups.length > 0) {
    return product.option_groups.map((group, gIdx) => ({
      id: group.id || `group_${gIdx}`,
      name: safeResolve(group.name, lang),
      required: Boolean(group.required),
      type: group.type || 'single',
      options: (group.options || []).map((opt, oIdx) => ({
        id: opt.id || `opt_${gIdx}_${oIdx}`,
        name: safeResolve(opt.name, lang),
        price: Number(opt.price || 0),
      })),
    }));
  }

  // 2. Synthesize option_groups from sizes & extras
  const syntheticGroups = [];

  if (Array.isArray(product.sizes) && product.sizes.length > 0) {
    syntheticGroups.push({
      id: 'size_selection',
      name: lang === 'tr' ? 'Boyut Seçimi' : 'Size Selection',
      required: true,
      type: 'single',
      options: product.sizes.map((s, idx) => ({
        id: `size_${idx}`,
        name: safeResolve(s.name, lang),
        price: Number(s.price || 0),
      })),
    });
  }

  if (Array.isArray(product.extras) && product.extras.length > 0) {
    const shots = product.extras.filter((e) => {
      const n = safeResolve(e.name, lang).toLowerCase();
      return n.includes('shot') || n.includes('şot');
    });
    const syrups = product.extras.filter((e) => {
      const n = safeResolve(e.name, lang).toLowerCase();
      return n.includes('şurup') || n.includes('syrup');
    });
    const others = product.extras.filter((e) => {
      const n = safeResolve(e.name, lang).toLowerCase();
      return !n.includes('shot') && !n.includes('şot') && !n.includes('şurup') && !n.includes('syrup');
    });

    if (shots.length > 0) {
      syntheticGroups.push({
        id: 'shot_selection',
        name: lang === 'tr' ? 'Extra Shot Seçimi' : 'Extra Shot Selection',
        required: false,
        type: 'single',
        options: shots.map((e, idx) => ({
          id: `shot_${idx}`,
          name: safeResolve(e.name, lang),
          price: Number(e.price || 0),
        })),
      });
    }

    if (syrups.length > 0) {
      syntheticGroups.push({
        id: 'syrup_selection',
        name: lang === 'tr' ? 'Şurup Seçimi' : 'Syrup Selection',
        required: false,
        type: 'multiple',
        options: syrups.map((e, idx) => ({
          id: `syrup_${idx}`,
          name: safeResolve(e.name, lang),
          price: Number(e.price || 0),
        })),
      });
    }

    if (others.length > 0) {
      syntheticGroups.push({
        id: 'extras_selection',
        name: lang === 'tr' ? 'Ekstra & Süt Seçimi' : 'Extras & Milk Selection',
        required: false,
        type: 'multiple',
        options: others.map((e, idx) => ({
          id: `extra_${idx}`,
          name: safeResolve(e.name, lang),
          price: Number(e.price || 0),
        })),
      });
    }
  }

  return syntheticGroups;
};

/**
 * Localization helper for products
 */
export const getLocalizedProduct = (product, lang = 'tr') => {
  if (!product) return null;

  return {
    ...product,
    name: safeResolve(product.name, lang),
    description: safeResolve(product.description, lang),
    sizes: (product.sizes || []).map((s) => ({
      ...s,
      name: safeResolve(s.name, lang),
    })),
    extras: (product.extras || []).map((e) => ({
      ...e,
      name: safeResolve(e.name, lang),
    })),
    optionGroups: getLocalizedOptionGroups(product, lang),
  };
};

